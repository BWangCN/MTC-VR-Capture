"""
Objaverse asset loader for procedural corridor environments.

Reads ``asset_registry.csv`` files under the BUNDLED asset directory
(``mtc_corridor/assets/objaverse/<room>_assets_usd/``) on first use and
serves random asset choices filtered by a target size envelope.

These assets are large (~700 MB/room) and are NOT committed -- they are
gitignored and (re)generated by ``scripts/objaverse/`` (see that dir's
README). If no registry/asset is found, ``load_objaverse_asset`` raises
``LookupError`` and the corridor generator falls back to procedural box
obstacles -- so the benchmark runs fully standalone without any download.

The registry CSV may store absolute USD paths from an older location;
this loader derives the CURRENT path from the registry's own directory +
(class, asset) keys and verifies file existence.

NB: file name retained as ``_objaverse_stub.py`` so existing imports keep
working; the module is no longer a stub.
"""

from __future__ import annotations

import csv
import os
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import numpy as np

# Bundled Objaverse asset directory. This file lives at
# <benchmark>/mtc_corridor/_objaverse_stub.py, so the benchmark root is two
# levels up; assets live under assets/objaverse/.
_ASSET_ROOT = Path(
    os.environ.get("MTC_OBJAVERSE_DIR")
    or (Path(__file__).resolve().parent.parent / "assets" / "objaverse")
)
# Primary: any room-style registry under the bundled asset dir (glob
# */asset_registry.csv -- whichever rooms were downloaded into the
# benchmark are picked up).
_REGISTRY_CANDIDATES = list(sorted(_ASSET_ROOT.glob("*/asset_registry.csv")))

# Fallback: the canonical SimEnv asset packs that live alongside the
# benchmark in Wayne's workspace (and on the Linux box once
# SimEnv/<room>/*_assets_usd_* is rsynced). Resolved via paths.REPO_ROOT
# so it's portable. If those dirs don't exist (fresh clone, no SimEnv),
# load_objaverse_asset gracefully returns LookupError -> procedural
# box fallback in make_ground / make_block_with_clutter.
try:
    from .paths import REPO_ROOT as _REPO_ROOT

    _SIMENV = _REPO_ROOT / "SimEnv"
    _SIMENV_FALLBACK = [
        _SIMENV / "bedroom" / "bedroom_assets_usd_simplified" / "asset_registry.csv",
        _SIMENV / "livingroom" / "livingroom_assets_usd_simplified" / "asset_registry.csv",
        _SIMENV / "kitchen" / "kitchen_assets_usd_simplified" / "asset_registry.csv",
        _SIMENV / "bedroom" / "bedroom_assets_usd_original" / "asset_registry.csv",
        _SIMENV / "livingroom" / "livingroom_assets_usd_original" / "asset_registry.csv",
        _SIMENV / "kitchen" / "kitchen_assets_usd_original" / "asset_registry.csv",
    ]
    # Append only if the corresponding registry actually exists on disk;
    # keeps the candidate list clean on machines that don't have these.
    for _p in _SIMENV_FALLBACK:
        if _p.exists() and _p not in _REGISTRY_CANDIDATES:
            _REGISTRY_CANDIDATES.append(_p)
except Exception:
    pass


@dataclass
class AssetRecord:
    cls: str
    asset: str
    usd_path: Path
    size_xyz: np.ndarray  # (sx, sy, sz) the AABB extents in metres
    center_xyz: np.ndarray  # (cx, cy, cz) the asset-local AABB center

    @property
    def height(self) -> float:
        return float(self.size_xyz[2])

    @property
    def footprint_xy(self) -> tuple[float, float]:
        return float(self.size_xyz[0]), float(self.size_xyz[1])


_REGISTRY_CACHE: Optional[dict[str, list[AssetRecord]]] = None


def _load_registry() -> dict[str, list[AssetRecord]]:
    """Load and cache all available registries on first call."""
    global _REGISTRY_CACHE
    if _REGISTRY_CACHE is not None:
        return _REGISTRY_CACHE

    by_class: dict[str, list[AssetRecord]] = {}
    # Track (class, asset) loaded so far so the original registry doesn't
    # duplicate entries already served from the simplified variant.
    seen: set[tuple[str, str]] = set()
    for csv_path in _REGISTRY_CANDIDATES:
        if not csv_path.exists():
            continue
        base = csv_path.parent
        with open(csv_path, "r", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                cls = row["class"].strip()
                asset = row["asset"].strip()
                if (cls, asset) in seen:
                    continue
                seen.add((cls, asset))
                # Derive USD path under CURRENT SimEnv location, not the
                # stale absolute path in the CSV.
                usd_path = base / cls / asset / f"{asset}.usd"
                if not usd_path.exists():
                    continue
                rec = AssetRecord(
                    cls=cls,
                    asset=asset,
                    usd_path=usd_path.resolve(),
                    size_xyz=np.array(
                        [
                            float(row["aabb_size_x_m"]),
                            float(row["aabb_size_y_m"]),
                            float(row["aabb_size_z_m"]),
                        ],
                        dtype=np.float64,
                    ),
                    center_xyz=np.array(
                        [
                            float(row["aabb_center_x_m"]),
                            float(row["aabb_center_y_m"]),
                            float(row["aabb_center_z_m"]),
                        ],
                        dtype=np.float64,
                    ),
                )
                by_class.setdefault(cls, []).append(rec)

    _REGISTRY_CACHE = by_class
    return by_class


def available_classes() -> list[str]:
    return sorted(_load_registry().keys())


def load_objaverse_asset(
    category: str,
    size_constraint: Optional[dict] = None,
    rng: Optional[random.Random] = None,
) -> AssetRecord:
    """Pick a random asset of `category` (or matching constraint) and return
    its record. Honours height_max / height_min / footprint_max filters.

    Args:
        category: Objaverse class hint, e.g. "book", "box", "shoes". Pass
            "any" or None to draw across all loaded classes.
        size_constraint: dict of optional filters:
            - height_min, height_max (metres) -- on aabb size_z
            - footprint_max_xy (metres)       -- max(size_x, size_y)
            - classes (list[str])             -- restrict to these classes
        rng: random.Random instance for determinism. Falls back to global.

    Returns:
        AssetRecord. Raises LookupError if nothing matches.
    """
    if rng is None:
        rng = random.Random()
    registry = _load_registry()
    if not registry:
        raise LookupError(
            "No Objaverse asset registry found. Expected one of: "
            + ", ".join(str(p) for p in _REGISTRY_CANDIDATES)
        )

    sc = size_constraint or {}
    classes_filter = sc.get("classes")
    h_min = sc.get("height_min", 0.0)
    h_max = sc.get("height_max", float("inf"))
    fp_max = sc.get("footprint_max_xy", float("inf"))

    if category in (None, "any"):
        cls_pool = list(registry.keys())
    else:
        cls_pool = [category]
    if classes_filter:
        cls_pool = [c for c in cls_pool if c in classes_filter]

    candidates: list[AssetRecord] = []
    for c in cls_pool:
        for rec in registry.get(c, ()):
            if rec.height < h_min or rec.height > h_max:
                continue
            if max(rec.footprint_xy) > fp_max:
                continue
            candidates.append(rec)

    # Optionally cap by source USD file size (VR poly-count proxy).
    max_file_mb = sc.get("max_file_mb", 8.0)
    if max_file_mb is not None:
        cap_bytes = int(max_file_mb * 1024 * 1024)
        candidates = [r for r in candidates if r.usd_path.stat().st_size <= cap_bytes]

    if not candidates:
        raise LookupError(
            f"No Objaverse asset matched category={category!r} "
            f"size_constraint={size_constraint!r} "
            f"(searched {len(cls_pool)} class(es))."
        )

    return rng.choice(candidates)
